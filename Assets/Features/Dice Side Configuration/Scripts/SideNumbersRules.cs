namespace Blackset.Data.Configurations
{
    /// <summary>
    /// Наименования правил конфигурации граней дайса для ручной настройки SideNumbersConfig
    /// </summary>
    public enum SideNumbersRules
    {
        // ── Базовые ──────────────────────────────────────────────────────────
        Default,

        // ── Математика (значения граней) ─────────────────────────────────────

        /// <summary>Все грани чётные (нечётные сдвигаются вверх на +1)</summary>
        Even,
        /// <summary>Все грани нечётные (чётные сдвигаются вниз на -1)</summary>
        Odd,
        /// <summary> Пиковый — количество крайних значений увеличено на N за счёт N ближайших к ним граней </summary>
        Peaked,
        /// <summary> Застрахованный — крайние значения отсутствуют; заменяются ближайшими в сторону МО </summary>
        Insured,
        /// <summary> Стабильный — N граней, ближайших к МО, заменяются значением МО </summary>
        Stable,

        // ── Экстремальные (крайности и смещение) ────────────────────────────

        /// <summary> Утяжелённый — максимальное значение куба +N, минимальное −N </summary>
        Weighted,
        /// <summary>Увеличенный — все грани куба +N</summary>
        Increased,
        /// <summary> Верхний — грани смещены в верхнюю половину (начинаются от МО, дублируются равномерно) </summary>
        Upper,
        /// <summary> Нижний — грани смещены в нижнюю половину (не выше МО, дублируются равномерно) </summary>
        Lower,
        /// <summary>Максимальный — все гарни максимальные</summary>
        AllMax,
        /// <summary>Минимальный — все гарни минимальные</summary>
        AllMin,
    }
}